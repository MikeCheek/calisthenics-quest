const XP = 5200;

// a realistic three weeks: sessions generated by the real generator
const FOCUS_ROTATION: SkillTrack[] = ["frontLever", "planche", "muscleUp", "handstand", "core", "backLever", "legs"];
const SESSION_DAYS = [1, 2, 4, 6, 8, 9, 11, 13, 15, 16, 18, 20];

export function demoSessions(): SessionRecord[] {
  return SESSION_DAYS.map((daysAgo, i) => {
    const focus = FOCUS_ROTATION[i % FOCUS_ROTATION.length];
    const s = generateSession(skills, DEFAULT_EQUIPMENT, focus, new Date(Date.now() - (daysAgo + away()) * DAY));
    const exercises = s.sets.flatMap((set) =>
      set.exercises.map((ex, j) => ({
        name: ex.name,
        setTitle: set.title,
        outcome: (i === 3 && j === 1 ? "tooHard" : i === 7 && j === 2 ? "skipped" : "done") as "done" | "tooHard" | "skipped",
        detail: ex.detail,
      }))
    );
    return {
      id: `demo-session-${i}`,
      finishedAt: iso(daysAgo, 17 + (i % 3)),
      focusLabel: s.focusLabel,
      durationMin: 38 + ((i * 7) % 20),
      xp: plannedXp(s),
      exercises,
      ...(i === 0 ? { records: [{ name: "Tuck front lever", kind: "hold" as const, value: 14, previous: 11 }] } : {}),
    };
  });
}

